const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
const output=path.resolve(process.env.QA_OUTPUT || 'test-results');
fs.mkdirSync(output,{recursive:true});
const assert=require('assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1512,height:1050},deviceScaleFactor:1});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.VLM_URL || 'http://127.0.0.1:5123/');
 await page.waitForFunction(()=>window.VLM,{timeout:30000});
 assert.equal(await page.locator('.point').count(),1000);
 const chooseEpoch=async value=>{
   const task=await page.evaluate(()=>VLM.getState().task);
   if(task==='t1') await page.locator(`#epoch-strip button[aria-label="Ver época ${value}"]`).click();
   else await page.selectOption('#epoch-select',String(value));
 };
 const showSettings=async()=>{if(!await page.locator('#view-settings').evaluate(e=>e.open))await page.locator('#view-settings summary').click();};
 const hideSettings=async()=>{if(await page.locator('#view-settings').evaluate(e=>e.open))await page.locator('#view-settings summary').click();};
 assert.equal(await page.locator('#inspector').isVisible(),false);
 assert.equal(await page.locator('#view-settings').evaluate(e=>e.open),false);
 assert.equal(await page.locator('#trail-style').isVisible(),false);
 assert.equal(await page.locator('#epoch-buttons').count(),0);
 assert.equal(await page.locator('#epoch-strip button').count(),7);
 assert.equal(await page.locator('#clear-filters').isVisible(),false);
 assert.equal(await page.locator('#clear-selection').isVisible(),false);
 assert.equal(await page.locator('#reset-view').isVisible(),false);
 assert.ok((await page.locator('#plot-wrap').boundingBox()).width>1150);
 await page.screenshot({path:output+'/overview.png',fullPage:true});
 const paintedPixels=()=>page.locator('#trails-canvas').evaluate(c=>{
   const bytes=c.getContext('2d').getImageData(0,0,c.width,c.height).data;
   let pixels=0;for(let i=3;i<bytes.length;i+=4)if(bytes[i])pixels++;
   return pixels;
 });
 assert.equal(await paintedPixels(),0,'Epoch 0 must not display any temporal trajectories');
 await page.locator('#chart-section').screenshot({path:output+'/epoch-zero.png'});
 await chooseEpoch(1);
 await page.waitForTimeout(800);
 assert.ok(await paintedPixels()>0,'Epoch 1 must show the first segment');
 assert.match(await page.locator('#chart-footnote').innerText(),/acumulado 0–1/);
 await showSettings();
 await page.check('#dim-initial');
 const dimmedInitial=await page.locator('#trails-canvas').evaluate(c=>c.toDataURL());
 await page.uncheck('#dim-initial');
 assert.notEqual(dimmedInitial,await page.locator('#trails-canvas').evaluate(c=>c.toDataURL()));
 const firstEpochTrail=await page.locator('#trails-canvas').evaluate(c=>c.toDataURL());
 await chooseEpoch(2);
 await page.waitForTimeout(800);
 assert.match(await page.locator('#chart-footnote').innerText(),/acumulado 0–2/);
 assert.notEqual(firstEpochTrail,await page.locator('#trails-canvas').evaluate(c=>c.toDataURL()));
 await chooseEpoch(0);
 await page.waitForTimeout(800);
 assert.equal(await paintedPixels(),0,'Returning to epoch 0 must remove both normal and highlighted trails');
 await page.selectOption('#trail-scope','full');
 assert.ok(await paintedPixels()>0,'Full overview is an explicit opt-in even at epoch 0');
 assert.match(await page.locator('#chart-footnote').innerText(),/Recorrido completo 0–20/);
 await page.selectOption('#trail-scope','current');
 assert.equal(await paintedPixels(),0);
 await page.selectOption('#layer','0');
 assert.equal(await page.evaluate(()=>VLM.getState().layer),0);
 await page.selectOption('#layer','3');
 assert.equal(await page.evaluate(()=>VLM.getState().layer),3);
 await chooseEpoch(20);
 await page.waitForTimeout(900);
 assert.equal(await page.evaluate(()=>VLM.getState().epochs.t1),6);
 await page.locator('#class-legend button').nth(3).click();
 assert.equal(await page.locator('#visible-count').innerText(),'100 / 1 000 imágenes');
 await page.check('#errors-only');
 assert.equal(await page.locator('#clear-filters').isVisible(),true);
 const errorCount=await page.evaluate(()=>VLM.data.samples.labels.filter((y,i)=>y===3&&VLM.data.experiments.base.predictions[6][i]!==y).length);
 assert.match(await page.locator('#visible-count').innerText(),new RegExp('^'+errorCount+' /'));
 assert.ok(await page.locator('.point[opacity="0"]').count()>900);
 await page.click('#clear-filters');
 const a=await page.locator('#trails-canvas').evaluate(c=>c.toDataURL());
 await page.selectOption('#trail-style','straight');
 const b=await page.locator('#trails-canvas').evaluate(c=>c.toDataURL());
 assert.notEqual(a,b);
 await page.selectOption('#trail-style','bundled');
 await page.locator('#strength').evaluate(e=>{e.value='80';e.dispatchEvent(new Event('input',{bubbles:true}));});
 assert.equal(await page.locator('#strength-value').innerText(),'80%');
 await page.locator('#strength').evaluate(e=>{e.value='45';e.dispatchEvent(new Event('input',{bubbles:true}));});
 await hideSettings();
 await page.screenshot({path:output+'/clean-overview.png',fullPage:true});
 const errorIndex=await page.evaluate(()=>VLM.data.samples.labels.findIndex((y,i)=>y===5&&VLM.data.experiments.base.predictions[6][i]===3));
 await page.locator(`.point[data-sample="${errorIndex}"]`).dispatchEvent('mouseenter');
 assert.equal(await page.locator('#inspector').isVisible(),false);
 await page.locator(`.point[data-sample="${errorIndex}"]`).dispatchEvent('click');
 assert.match(await page.locator('#sample-id').innerText(),/MNIST #/);
 assert.equal(await page.locator('#inspector').isVisible(),true);
 assert.equal(await page.locator('#prediction-history button').count(),0);
 assert.equal(await page.locator('#prediction-history .prediction-cell').count(),7);
 assert.equal(await page.locator('#true-label').innerText(),'5');
 assert.equal(await page.locator('#pred-label').innerText(),'3');
 await page.locator('#class-legend button').nth(0).click();
 assert.match(await page.locator('#sample-id').innerText(),/fuera del filtro/);
 assert.equal(await page.locator(`.point[data-sample="${errorIndex}"]`).getAttribute('opacity'),'0');
 await page.click('#clear-filters');
 assert.doesNotMatch(await page.locator('#sample-id').innerText(),/fuera del filtro/);
 assert.equal(await page.locator('#neighbors button').count(),6);
 await page.screenshot({path:output+'/detail.png',fullPage:true});
 await page.click('#unpin');
 assert.equal(await page.locator('#inspector').isVisible(),false);
 await page.click('#mode-brush');
 const box=await page.locator('#plot-wrap').boundingBox();
 await page.mouse.move(box.x+box.width*.3,box.y+box.height*.25);
 await page.mouse.down();
 await page.mouse.move(box.x+box.width*.7,box.y+box.height*.75,{steps:14});
 await page.mouse.up();
 await page.waitForTimeout(300);
 const selected=await page.evaluate(()=>VLM.getState().selected.length);
 assert.ok(selected>0);
 assert.equal(await page.locator('#gallery').getByRole('button').count(),Math.min(30,selected));
 await page.screenshot({path:output+'/brush.png',fullPage:true});
 await page.click('#clear-selection');
 await page.click('#mode-pan');
 await page.locator('#plot').hover();
 await page.mouse.wheel(0,-350);
 await page.waitForTimeout(400);
 assert.ok(await page.evaluate(()=>VLM.getState().transform.k)>1);
 await page.click('#reset-view');
 await page.waitForTimeout(100);
 assert.equal(await page.evaluate(()=>VLM.getState().transform.k),1);
 await page.click('#tab-t2');
 await page.waitForTimeout(300);
 assert.equal(await page.locator('.point').count(),4000);
 assert.equal(await page.locator('#epoch-control').isVisible(),true);
 assert.equal(await page.locator('#epoch-strip').isVisible(),false);
 await chooseEpoch(2);
 assert.equal(await page.evaluate(()=>VLM.getState().epochs.t2),2);
 await chooseEpoch(20);
 await page.waitForTimeout(200);
 assert.equal(await page.locator('#full-trails-control').isVisible(),false);
 assert.equal(await page.locator('#dim-initial-control').isVisible(),false);
 await page.locator(`.point[data-sample="${errorIndex}"]`).nth(0).dispatchEvent('click');
 assert.equal(await page.evaluate(()=>VLM.getState().detailLayer),0);
 assert.equal(await page.locator('#true-label').innerText(),'5');
 await page.screenshot({path:output+'/layers-detail.png',fullPage:true});
 await page.click('#unpin');
 await showSettings();
 await page.selectOption('#speed','650');
 await hideSettings();
 await page.click('#play');
 await page.waitForTimeout(750);
 await page.click('#play');
 assert.equal(await page.evaluate(()=>VLM.getState().playing),false);
 assert.equal(await page.evaluate(()=>VLM.getState().reveal),1);
 await page.click('#play');
 await page.waitForTimeout(1500);
 assert.equal(await page.evaluate(()=>VLM.getState().reveal),3);
 assert.equal(await page.evaluate(()=>VLM.getState().playing),false);
 await page.locator('#diagnostics summary').click();
 await page.waitForTimeout(200);
 assert.equal(await page.locator('.matrix-cell').count(),200);
 await page.locator('.matrix-item').nth(0).locator('.matrix-cell').nth(53).click();
 await page.waitForTimeout(150);
 assert.deepEqual(await page.evaluate(()=>VLM.getState().confusion),[5,3]);
 assert.equal(await page.evaluate(()=>VLM.getState().selected.length),3);
 await page.screenshot({path:output+'/confusions.png',fullPage:true});
 await page.selectOption('#experiment','refined');
 assert.equal(await page.evaluate(()=>VLM.getState().experiment),'refined');
 if(await page.locator('#clear-filters').isVisible())await page.click('#clear-filters');
 if(await page.locator('#clear-selection').isVisible())await page.click('#clear-selection');
 await page.click('#tab-t1');
 await chooseEpoch(0);
 await showSettings();
 await page.selectOption('#speed','650');
 await hideSettings();
 await page.click('#play');
 await page.waitForTimeout(850);
 await page.click('#play');
 assert.equal(await page.evaluate(()=>VLM.getState().playing),false);
 assert.ok(await page.evaluate(()=>VLM.getState().epochs.t1)>0);
 await page.click('#method-open');
 assert.ok(await page.locator('#method-dialog').isVisible());
 await page.locator('#method-dialog .dialog-close').click();
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(350);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth)<=390);
 await page.screenshot({path:output+'/mobile-t1.png',fullPage:true});
 await page.click('#tab-t2');await page.waitForTimeout(250);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth)<=390);
 await page.screenshot({path:output+'/mobile-t2.png',fullPage:true});
 console.log(JSON.stringify({status:'passed',errors,errorCount,brushCount:selected,coverage:'cohort, layers, epochs, filters, bundling, details, brush, zoom, playback, matrices, experiments, mobile'}));
 assert.deepEqual(errors,[]);
 fs.writeFileSync(output+'/browser-result.json',JSON.stringify({status:'passed',coverage:'cohort, layers, epochs, filters, bundling, details, brush, zoom, playback, matrices, experiments, mobile',errors,brushCount:selected},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
